/**
 * WHITE NOON — gen-tz-coords (SKY-5, run ONCE; output is committed)
 * Parses the vendored IANA zone1970.tab (public domain) into a compact
 * timezone → [lat, lon] table consumed by weather.js: the user's
 * Intl.DateTimeFormat().resolvedOptions().timeZone resolves to coordinates
 * WITHOUT any geolocation permission and WITHOUT the (forbidden) Geocoding
 * API — CONTRACTS §f.4. Coordinates are the zone's principal city, rounded
 * to 2 decimals (≈1 km — plenty for weather). ~340 zones ≈ 4 KB gz.
 *
 *   node scripts/gen-tz-coords.mjs
 *   → src/field-conditions/tz-coords.js
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = new URL('./data/zone1970.tab', import.meta.url);
const OUT = new URL('../src/field-conditions/tz-coords.js', import.meta.url);

// ISO 6709 ±DDMM±DDDMM | ±DDMMSS±DDDMMSS → [lat, lon] decimal degrees
function iso6709(s) {
  const m = s.match(/^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/);
  if (!m) throw new Error('unparsable coordinates: ' + s);
  const lat = (+m[2] + m[3] / 60 + (m[4] ? m[4] / 3600 : 0)) * (m[1] === '-' ? -1 : 1);
  const lon = (+m[6] + m[7] / 60 + (m[8] ? m[8] / 3600 : 0)) * (m[5] === '-' ? -1 : 1);
  return [+lat.toFixed(2), +lon.toFixed(2)];
}

const rows = readFileSync(SRC, 'utf8').split('\n')
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => l.split('\t'))
  .filter((c) => c.length >= 3);

const entries = rows.map(([, coords, tz]) => `'${tz}':[${iso6709(coords).join(',')}]`);

const body = `/**
 * WHITE NOON — tz-coords (GENERATED by scripts/gen-tz-coords.mjs — do not edit)
 * Source: IANA zone1970.tab (public domain), vendored at scripts/data/zone1970.tab.
 * timezone → [lat, lon] of the zone's principal location (2-decimal rounding).
 * weather.js uses it for (a) the Open-Meteo coordinates and (b) the hemisphere
 * (lat < 0 → seasons shifted +6 months). No match → synthetic Layer 0 only.
 */
export const TZ_COORDS = {
${entries.join(',\n')},
};
`;

writeFileSync(OUT, body);
console.log(`tz-coords.js written: ${entries.length} zones, ${(body.length / 1024).toFixed(1)} KB raw`);
